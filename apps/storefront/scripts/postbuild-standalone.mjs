/**
 * Make `output: "standalone"` directly runnable on a managed host.
 *
 * Next leaves two gaps that matter here:
 *
 * 1. It deliberately does not copy `public/` or `.next/static` into the
 *    standalone bundle, so a standalone server started as-is returns 404 for
 *    every image and asset.
 * 2. In a monorepo the entry point is emitted at
 *    `.next/standalone/apps/storefront/server.js`, because tracing is rooted at
 *    the repo (node_modules is hoisted there). Hostinger's Next.js preset boots
 *    `.next/standalone/server.js`, so that path has to exist too.
 *
 * This script closes both gaps after `next build`. It is idempotent.
 */
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const appDir = path.join(path.dirname(fileURLToPath(import.meta.url)), "..")
const standaloneRoot = path.join(appDir, ".next", "standalone")

if (!fs.existsSync(standaloneRoot)) {
  console.log("postbuild: no standalone output, skipping")
  process.exit(0)
}

// Where the traced app actually landed: nested under the repo-relative path in a
// monorepo, or at the standalone root for a single-package build.
const repoRoot = path.join(appDir, "..", "..")
const relFromRepo = path.relative(repoRoot, appDir)
const nestedAppDir = path.join(standaloneRoot, relFromRepo)
const targetDir = fs.existsSync(nestedAppDir) ? nestedAppDir : standaloneRoot

/** Copy a build artefact into the standalone bundle. */
function copyInto(relative) {
  const from = path.join(appDir, relative)
  const to = path.join(targetDir, relative)

  if (!fs.existsSync(from)) {
    console.log(`postbuild: ${relative} not found, skipping`)
    return
  }

  fs.rmSync(to, { recursive: true, force: true })
  fs.mkdirSync(path.dirname(to), { recursive: true })
  fs.cpSync(from, to, { recursive: true })
  console.log(`postbuild: copied ${relative}`)
}

copyInto("public")
copyInto(path.join(".next", "static"))

// Entry-point shim, only needed when the real server is nested.
if (targetDir !== standaloneRoot) {
  const entry = path.join(standaloneRoot, "server.js")
  const target = `./${path
    .join(relFromRepo, "server.js")
    .split(path.sep)
    .join("/")}`

  fs.writeFileSync(
    entry,
    `// Generated by scripts/postbuild-standalone.mjs — do not edit.\n` +
      `// Hosts that boot \`.next/standalone/server.js\` land here; the traced\n` +
      `// entry point lives under the workspace path in a monorepo build.\n` +
      `require(${JSON.stringify(target)})\n`
  )
  console.log(`postbuild: wrote entry shim -> ${target}`)
}

console.log("postbuild: standalone bundle ready")
